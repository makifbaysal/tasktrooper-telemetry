const r3 = 9601

const (
	r3StreamRemote = 9601001 // odd  → shard 1 (engine B)
	r3StreamLocal  = 9601002 // even → shard 0 (engine A, stream leader)
	r3EvalRemote   = 9601003 // odd  → shard 1
	r3Code         = 9601004 // even → shard 0: alert-as-code monitor, Slack App target
	r3Kpi          = 9601002 // kpis id (even → shard 0)
	slackTarget    = "slack:C0R3ALERT#r3-alerts"
)

func cleanupR3(t *testing.T, ctx context.Context, pg *pgxpool.Pool, ch driver.Conn) {
	t.Helper()
	for _, q := range []string{
		`DELETE FROM notification_messages WHERE incident_id IN (SELECT id FROM incidents WHERE project_id = 9601)`,
		`DELETE FROM alert_stream_hits WHERE monitor_id IN (SELECT id FROM monitors WHERE project_id = 9601)`,
		`DELETE FROM projects WHERE id = 9601`,
		`DELETE FROM orgs WHERE id = 9601`,
	} {
		if _, err := pg.Exec(ctx, q); err != nil && !strings.Contains(err.Error(), "does not exist") {
			t.Fatalf("pg cleanup: %v\n%s", err, q)
		}
	}
	mctx := clickhouse.Context(ctx, clickhouse.WithSettings(clickhouse.Settings{"mutations_sync": 2}))
	for _, tbl := range chTables {
		if err := ch.Exec(mctx, "ALTER TABLE telemetry."+tbl+" DELETE WHERE project_id = 9601"); err != nil {
			t.Fatalf("ch cleanup %s: %v", tbl, err)
		}
	}
}

// TestRound3 covers, on org/project 9601 with two alert-engine shards:
//   - multi-shard stream rules: the stream leader (shard 0) evaluates every stream rule; a hit on shard 1's monitor
//     is handed off through alert_stream_hits + NOTIFY tt_stream_hit and fires on engine B within ~1 s;
//   - KPI rule reminders (kpi_alert_rules.condition.renotifyMin);
//   - alert-as-code monitors (source/code_ref) evaluate normally and carry codeRef, root cause confidence and deploy
//     context in the payload;
//   - Slack App delivery (fake Slack API): firing message, acknowledged + reminder thread replies.
func TestRound3(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()
	common := config.Load()
	pg, err := conn.Postgres(ctx, common.PostgresURL)
	if err != nil {
		t.Skipf("postgres unavailable: %v", err)
	}
	t.Cleanup(pg.Close)
	ch, err := conn.ClickHouse(ctx, common.ClickHouseURL)
	if err != nil {
		t.Skipf("clickhouse unavailable: %v", err)
	}
	t.Cleanup(func() { _ = ch.Close() })
	exec := func(q string, args ...any) {
		t.Helper()
		if _, err := pg.Exec(ctx, q, args...); err != nil {
			t.Fatalf("%v\n%s", err, q)
		}
	}
	// Columns / tables owned by other migrations (005 alert-as-code, 009 Slack/GitHub): created defensively.
	// What this test creates is dropped again afterwards so the owning migration applies unchanged.
	var hadMessages bool
	_ = pg.QueryRow(ctx, `SELECT to_regclass('notification_messages') IS NOT NULL`).Scan(&hadMessages)
	exec(`ALTER TABLE monitors ADD COLUMN IF NOT EXISTS code_ref text`)
	exec(`CREATE TABLE IF NOT EXISTS notification_messages (
		id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, incident_id bigint REFERENCES incidents(id) ON DELETE CASCADE,
		channel text NOT NULL, provider text NOT NULL, external_id text NOT NULL, external_channel text, created_at timestamptz NOT NULL DEFAULT now())`)
	cleanupR3(t, ctx, pg, ch)
	if os.Getenv("TT_ITEST_KEEP") == "" {
		t.Cleanup(func() { cleanupR3(t, context.Background(), pg, ch) })
	}
	if !hadMessages {
		t.Cleanup(func() { _, _ = pg.Exec(context.Background(), `DROP TABLE IF EXISTS notification_messages`) })
	}

	// ── fake Slack Web API ──
	var mu sync.Mutex
	type call struct {
		method string
		body   map[string]any
	}
	var calls []call
	slack := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		b, _ := io.ReadAll(r.Body)
		var body map[string]any
		_ = json.Unmarshal(b, &body)
		mu.Lock()
		calls = append(calls, call{strings.TrimPrefix(r.URL.Path, "/api/"), body})
		n := len(calls)
		mu.Unlock()
		if r.Header.Get("Authorization") != "Bearer xoxb-r3" {
			_, _ = w.Write([]byte(`{"ok":false,"error":"invalid_auth"}`))
			return
		}
		_, _ = w.Write([]byte(`{"ok":true,"channel":"C0R3ALERT","ts":"1700000000.00` + itoa(int64(n)) + `"}`))
	}))
	defer slack.Close()

	exec(`INSERT INTO orgs (id, name) VALUES (9601, 'itest r3')`)
	exec(`INSERT INTO projects (id, org_id, name, slug) VALUES (9601, 9601, 'itest r3', 'itest-r3')`)
	key, err := secrets.Key()
	if err != nil {
		t.Fatal(err)
	}
	nonce, sealed, err := secrets.Seal(key, r3, []byte("xoxb-r3"))
	if err != nil {
		t.Fatal(err)
	}
	var tokenID int64
	if err := pg.QueryRow(ctx, `INSERT INTO secrets (project_id, name, nonce, ciphertext) VALUES (9601, 'slack bot token', $1, $2) RETURNING id`, nonce, sealed).Scan(&tokenID); err != nil {
		t.Fatal(err)
	}
	insSlack := `INSERT INTO integrations (project_id, provider, name, config, credentials_ref, status) VALUES (9601, 'slack', 'Acme', '{"teamId":"T1"}', $1, 'ok')`
	if _, err := pg.Exec(ctx, insSlack, "secret:"+itoa(tokenID)); err != nil && strings.Contains(err.Error(), "integrations_provider_check") {
		// 009_slack_github.sql not applied yet: allow the provider like it does
		exec(`ALTER TABLE integrations DROP CONSTRAINT IF EXISTS integrations_provider_check`)
		exec(`ALTER TABLE integrations ADD CONSTRAINT integrations_provider_check CHECK (provider IN ('aws', 'gcp', 'vercel', 'neon', 'slack', 'github'))`)
		t.Cleanup(func() { // after cleanupR3 removed the row (cleanups run last-in first-out)
			bg := context.Background()
			_, _ = pg.Exec(bg, `DELETE FROM integrations WHERE provider IN ('slack', 'github') AND project_id = 9601`)
			_, _ = pg.Exec(bg, `ALTER TABLE integrations DROP CONSTRAINT IF EXISTS integrations_provider_check`)
			_, _ = pg.Exec(bg, `ALTER TABLE integrations ADD CONSTRAINT integrations_provider_check CHECK (provider IN ('aws', 'gcp', 'vercel', 'neon'))`)
		})
		exec(insSlack, "secret:"+itoa(tokenID))
	} else if err != nil {
		t.Fatal(err)
	}

	now := time.Now().UTC().Truncate(time.Minute).Add(20 * time.Second)
	to := now.Truncate(time.Minute)
	ent := func(svc, route string, errEvery int) span {
		return span{service: svc, kind: "server", entry: true, route: route, method: "GET", entryRoute: route, caller: "web", durMs: 50, errEvery: errEvery, version: "v1"}
	}
	insertSpansIn(t, ctx, ch, r3, ent("r3-api", "/kpi", 2), to.Add(-10*time.Minute), 10, 20)
	insertSpansIn(t, ctx, ch, r3, ent("r3-api", "/code", 2), to.Add(-10*time.Minute), 10, 20)
	exec(`INSERT INTO deploy_markers (project_id, service, version, source, author, commit_message, ts, external_id) VALUES
		(9601, 'r3-api', 'r3sha1', 'ci', 'ayse', 'tune pool', $1, 'r3-1')`, now.Add(-10*time.Minute))

	// ── monitors (explicit ids pick the shard: id % 2) ──
	addMon := func(id int64, name, kind, target, query, cond string, channels ...string) {
		t.Helper()
		exec(`INSERT INTO monitors (id, project_id, name, kind, target, query, condition, severity, channels, source)
			VALUES ($1, 9601, $2, $3, $4, $5, $6, 'critical', $7, 'manual')`, id, name, kind, target, query, cond, append([]string{}, channels...))
	}
	streamCond := `{"threshold":2,"window":"5m","stream":true}`
	addMon(r3StreamRemote, "remote boom", "log_match", `{"service":"r3-api"}`, `{"contains":"boom","minSeverity":"error"}`, streamCond)
	addMon(r3StreamLocal, "local boom", "log_match", `{"service":"r3-api"}`, `{"contains":"boom","minSeverity":"error"}`, streamCond)
	addMon(r3EvalRemote, "remote fuzzy", "log_match", `{"service":"r3-api"}`, `{"pattern":"boo.*","minSeverity":"error"}`, streamCond)
	addMon(r3Code, "code errors", "error_rate", `{"service":"r3-api","endpoint":"GET /code"}`, `{}`, `{"op":">","threshold":0.1,"window":"5m"}`, slackTarget)
	exec(`UPDATE monitors SET code_ref = 'acme/shop:.trooper/monitors/code.yaml' WHERE id = $1`, r3Code)
	if _, err := pg.Exec(ctx, `UPDATE monitors SET source = 'code' WHERE id = $1`, r3Code); err != nil {
		t.Logf("source='code' not allowed yet (005 not applied): %v", err)
	}
	exec(`INSERT INTO kpis (id, project_id, name, target, sli, good_when, objective, "window", source)
		VALUES ($1, 9601, 'KPI endpoint succeeds', '{"kind":"endpoint","service":"r3-api","ref":"GET /kpi"}', 'availability', '{}', 0.99, '28d', 'manual')`, r3Kpi)
	var ruleID int64
	if err := pg.QueryRow(ctx, `INSERT INTO kpi_alert_rules (kpi_id, kind, long_window, short_window, threshold, severity, channels, condition)
		VALUES ($1, 'burn_rate', '1h', '5m', 6, 'critical', $2, '{"renotifyMin":5}') RETURNING id`, r3Kpi, []string{slackTarget}).Scan(&ruleID); err != nil {
		t.Fatal(err)
	}

	// ── two engines, two shards ──
	log := slog.New(slog.NewTextHandler(os.Stderr, &slog.HandlerOptions{Level: slog.LevelInfo}))
	reg := obs.NewRegistry()
	base := leader.DefaultBase + 9601_001
	elA := &leader.Elector{Pool: pg, Base: base, Shards: 2, MaxPerInstance: 1}
	elB := &leader.Elector{Pool: pg, Base: base, Shards: 2, MaxPerInstance: 1}
	defer elA.Release()
	defer elB.Release()
	cfg := engine.Config{ProjectIDs: []int64{r3}, PublicURL: "http://dash.local"}
	st := &store.Store{DB: pg}
	engA := engine.New(cfg, log.With("engine", "A"), st, ch, elA, reg)
	engB := engine.New(cfg, log.With("engine", "B"), st, ch, elB, reg)
	for _, e := range []*engine.Engine{engA, engB} {
		e.Now = func() time.Time { return now }
		if err := e.Tick(ctx); err != nil {
			t.Fatal(err)
		}
	}
	if !engA.StreamLeader() || engB.StreamLeader() || !engB.Leader() {
		t.Fatalf("shards: A stream leader=%v, B stream leader=%v leader=%v", engA.StreamLeader(), engB.StreamLeader(), engB.Leader())
	}
	var ids []int64
	for _, m := range engA.StreamMonitors() {
		ids = append(ids, m.ID)
	}
	if len(ids) != 3 {
		t.Fatalf("stream leader must evaluate all stream rules, got %v", ids)
	}
	if n := len(engB.StreamMonitors()); n != 2 {
		t.Fatalf("engine B stream monitors (own shard only) = %d", n)
	}

	state := func(id int64) string {
		var s string
		_ = pg.QueryRow(ctx, `SELECT state FROM monitors WHERE id = $1`, id).Scan(&s)
		return s
	}
	// owner side listens
	hctx, hstop := context.WithCancel(ctx)
	hdone := make(chan struct{})
	go func() { engB.RunStreamHandoff(hctx, pg); close(hdone) }()
	defer func() { hstop(); <-hdone }()
	time.Sleep(300 * time.Millisecond) // LISTEN established

	// ── stream: three "boom" errors through the stream leader's processor ──
	lrs := []*logspb.LogRecord{}
	for range 3 {
		lrs = append(lrs, &logspb.LogRecord{SeverityNumber: logspb.SeverityNumber_SEVERITY_NUMBER_ERROR,
			Body: &commonpb.AnyValue{Value: &commonpb.AnyValue_StringValue{StringValue: "boom in handler"}}})
	}
	b, _ := proto.Marshal(&collogspb.ExportLogsServiceRequest{ResourceLogs: []*logspb.ResourceLogs{{
		Resource:  &resourcepb.Resource{Attributes: []*commonpb.KeyValue{{Key: "service.name", Value: &commonpb.AnyValue{Value: &commonpb.AnyValue_StringValue{StringValue: "r3-api"}}}}},
		ScopeLogs: []*logspb.ScopeLogs{{LogRecords: lrs}},
	}}})
	sp := stream.NewProcessor(engA, reg, log)
	sp.Refresh()
	start := time.Now()
	sp.Handle(ctx, &kgo.Record{Topic: "tt.otlp.logs", Value: b, Headers: []kgo.RecordHeader{{Key: "project_id", Value: []byte("9601")}}})
	if s := state(r3StreamLocal); s != "firing" {
		t.Errorf("local stream rule: %s", s)
	}
	var handoff time.Duration
	for time.Since(start) < 5*time.Second {
		if state(r3StreamRemote) == "firing" {
			handoff = time.Since(start)
			break
		}
		time.Sleep(50 * time.Millisecond)
	}
	t.Logf("remote stream rule fired after %s", handoff)
	if handoff == 0 || handoff > 1500*time.Millisecond {
		t.Errorf("remote stream rule via hand-off: state %s after %s", state(r3StreamRemote), time.Since(start))
	}
	var fired int
	_ = pg.QueryRow(ctx, `SELECT count(*) FROM incidents WHERE monitor_id = $1 AND state = 'firing'`, r3StreamRemote).Scan(&fired)
	if fired != 1 {
		t.Errorf("remote incident count %d", fired)
	}
	// non-exact rule (regex): the leader's ClickHouse re-check is handed off as an 'eval' hit and claimed by B
	for _, m := range engA.StreamMonitors() {
		if m.ID == r3EvalRemote {
			engA.EvalNow(ctx, m)
		}
	}
	deadline := time.Now().Add(3 * time.Second)
	var left int
	for time.Now().Before(deadline) {
		_ = pg.QueryRow(ctx, `SELECT count(*) FROM alert_stream_hits WHERE monitor_id = $1`, r3EvalRemote).Scan(&left)
		if left == 0 {
			break
		}
		time.Sleep(50 * time.Millisecond)
	}
	if left != 0 {
		t.Errorf("eval hit not claimed by the owner")
	}

	// ── code monitor + KPI rule fired on tick 1 (engine A owns both) ──
	if s := state(r3Code); s != "firing" {
		t.Fatalf("code monitor state %s", s)
	}
	var payload []byte
	var rcConf *float64
	if err := pg.QueryRow(ctx, `SELECT n.payload, (i.root_cause->>'confidence')::float8 FROM notifications n JOIN incidents i ON i.id = n.incident_id
		WHERE i.monitor_id = $1 AND n.kind = 'firing'`, r3Code).Scan(&payload, &rcConf); err != nil {
		t.Fatalf("code monitor notification: %v", err)
	}
	var p notify.Payload
	_ = json.Unmarshal(payload, &p)
	if p.CodeRef != "acme/shop:.trooper/monitors/code.yaml" || p.Deploy == nil || p.Deploy.Version != "r3sha1" {
		t.Errorf("code monitor payload %s", payload)
	}
	if rcConf == nil || p.RootCause == nil || p.RootCause.Confidence == nil || *p.RootCause.Confidence != *rcConf {
		t.Errorf("root cause (with confidence) must be stored before the firing notification and carried: stored %v payload %s", rcConf, payload)
	}
	var kpiInc int64
	_ = pg.QueryRow(ctx, `SELECT id FROM incidents WHERE kpi_rule_id = $1 AND state = 'firing'`, ruleID).Scan(&kpiInc)
	if kpiInc == 0 {
		t.Fatal("kpi rule did not fire")
	}

	// ── notifier with the fake Slack API: firing messages for the code monitor and the KPI rule ──
	res := notify.NewSecretResolver(st, key)
	d := notify.NewDeliverer(notify.SMTPConfig{})
	d.Slack = &notify.SlackApp{Base: slack.URL + "/api", Store: &notify.PGSlackStore{DB: pg, Secrets: res}, PublicAppURL: "http://dash.local"}
	w := &notify.Worker{DB: pg, D: d, Log: log, Reg: reg, Secrets: res}
	drain := func() {
		t.Helper()
		if _, err := w.Once(ctx); err != nil {
			t.Fatal(err)
		}
		var failed string
		_ = pg.QueryRow(ctx, `SELECT coalesce(string_agg(channel || ': ' || error, '; '), '') FROM notifications n JOIN incidents i ON i.id = n.incident_id
			WHERE i.project_id = 9601 AND n.sent_at IS NULL AND n.error IS NOT NULL`).Scan(&failed)
		if failed != "" {
			t.Fatalf("undelivered: %s", failed)
		}
	}
	drain()
	mu.Lock()
	if len(calls) != 2 || calls[0].method != "chat.postMessage" || calls[0].body["channel"] != "C0R3ALERT" {
		t.Fatalf("slack calls %+v", calls)
	}
	var bodies []map[string]any
	for _, c := range calls {
		bodies = append(bodies, c.body)
	}
	all, _ := json.Marshal(bodies)
	mu.Unlock()
	for _, want := range []string{"Firing: code errors", "tt_ack:", "tt_mute1h:" + itoa(r3Code), "acme/shop:.trooper/monitors/code.yaml", "r3sha1", "KPI endpoint succeeds"} {
		if !strings.Contains(string(all), want) {
			t.Errorf("slack messages lack %q", want)
		}
	}
	var refs int
	_ = pg.QueryRow(ctx, `SELECT count(*) FROM notification_messages m JOIN incidents i ON i.id = m.incident_id WHERE i.project_id = 9601 AND m.provider = 'slack'`).Scan(&refs)
	if refs != 2 {
		t.Errorf("notification_messages rows %d", refs)
	}

	// ── ack the code incident (dashboard / Slack button) → thread reply; +6 min → KPI reminder in its thread ──
	exec(`UPDATE incidents SET state = 'acknowledged', acked_at = now() WHERE monitor_id = $1 AND state = 'firing'`, r3Code)
	for _, e := range []*engine.Engine{engA, engB} {
		e.Now = func() time.Time { return now.Add(6 * time.Minute) }
		if err := e.Tick(ctx); err != nil {
			t.Fatal(err)
		}
	}
	var kpiRem int
	_ = pg.QueryRow(ctx, `SELECT count(*) FROM notifications WHERE incident_id = $1 AND kind = 'reminder'`, kpiInc).Scan(&kpiRem)
	if kpiRem != 1 {
		t.Errorf("kpi reminders %d, want 1", kpiRem)
	}
	if err := engA.Tick(ctx); err != nil { // same slot: idempotent (reminder + ack)
		t.Fatal(err)
	}
	drain()
	mu.Lock()
	defer mu.Unlock()
	var acks, reminders, updates int
	for _, c := range calls[2:] {
		switch {
		case c.method == "chat.update":
			updates++
		case c.body["thread_ts"] != nil && strings.HasPrefix(c.body["text"].(string), "👀 Acknowledged"):
			acks++
		case c.body["thread_ts"] != nil && strings.HasPrefix(c.body["text"].(string), "🔁 Still firing (reminder 1)"):
			reminders++
		}
	}
	if acks != 1 || reminders != 1 || updates != 2 {
		t.Errorf("thread replies: acks=%d reminders=%d updates=%d (%d calls)", acks, reminders, updates, len(calls))
	}
}
