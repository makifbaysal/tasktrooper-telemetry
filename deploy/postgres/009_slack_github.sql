-- Slack App + GitHub App integrations (ADR-017, contracts §17/§18). Owner: services/api. Additive and idempotent.

-- Slack: one installation per org (row in the installing project, read org-wide; credentials_ref = bot token).
--   config = { "teamId": "T…", "teamName": "Acme", "botUserId": "U…", "scopes": "chat:write,…" }
-- GitHub: one row per App installation and project.
--   config = { "installationId": 123, "account": "acme", "accountType": "Organization" }
ALTER TABLE integrations DROP CONSTRAINT IF EXISTS integrations_provider_check;
ALTER TABLE integrations ADD CONSTRAINT integrations_provider_check CHECK (provider IN ('aws', 'gcp', 'vercel', 'neon', 'slack', 'github'));
CREATE INDEX IF NOT EXISTS integrations_github_installation ON integrations ((config->>'installationId')) WHERE provider = 'github';

-- Slack messages of an incident: the first message's ts; resolve / reminder / ack go to its thread (notifier).
CREATE TABLE IF NOT EXISTS notification_messages (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id       bigint NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    channel           text NOT NULL,                       -- notification target, e.g. slack:C0123ABCD#payments-alerts
    provider          text NOT NULL DEFAULT 'slack',
    external_id       text NOT NULL,                       -- slack message ts
    external_channel  text NOT NULL,                       -- slack channel id
    created_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (incident_id, channel, provider)
);

-- GitHub push webhook → changed files for an incremental analysis (codeintel); removed from the installation → disconnected.
ALTER TABLE repositories ADD COLUMN IF NOT EXISTS pending_paths text[];
ALTER TABLE repositories DROP CONSTRAINT IF EXISTS repositories_status_check;
ALTER TABLE repositories ADD CONSTRAINT repositories_status_check CHECK (status IN ('pending', 'analyzing', 'ready', 'error', 'disconnected'));
