-- Load testing (ADR-015, contracts §14): run control columns, verified target domains, monthly usage and
-- per-region runner shards. Owner: services/loadtest. Additive and idempotent.

ALTER TABLE loadtest_runs ADD COLUMN IF NOT EXISTS region             text;          -- regions of the run, comma separated
ALTER TABLE loadtest_runs ADD COLUMN IF NOT EXISTS live               jsonb;         -- { ts, vus, rps, p95, errorRate, progress }
ALTER TABLE loadtest_runs ADD COLUMN IF NOT EXISTS abort_requested_at timestamptz;   -- api POST /loadtests/runs/{id}/stop
ALTER TABLE loadtest_runs ADD COLUMN IF NOT EXISTS error              text;          -- state = 'error' reason
ALTER TABLE loadtest_runs ADD COLUMN IF NOT EXISTS created_at         timestamptz NOT NULL DEFAULT now();
ALTER TABLE loadtest_runs ADD COLUMN IF NOT EXISTS requested_by       bigint;
ALTER TABLE loadtest_runs ADD COLUMN IF NOT EXISTS claimed_by         text;          -- loadtest-ctl instance
ALTER TABLE loadtest_runs ADD COLUMN IF NOT EXISTS vu_minutes         numeric;       -- actual usage once finished

CREATE INDEX IF NOT EXISTS loadtest_runs_state_idx ON loadtest_runs (state) WHERE state IN ('queued', 'running');

CREATE TABLE IF NOT EXISTS loadtest_domains (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id          bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    host                text NOT NULL,
    token               text NOT NULL,
    verified_at         timestamptz,
    method              text CHECK (method IN ('dns', 'http')),
    created_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, host)
);
-- verification requests (api POST /loadtests/domains/{id}/verify sets verify_requested_at = now()); the
-- loadtest-ctl worker checks DNS TXT / .well-known and records the outcome.
ALTER TABLE loadtest_domains ADD COLUMN IF NOT EXISTS verify_requested_at timestamptz;
ALTER TABLE loadtest_domains ADD COLUMN IF NOT EXISTS last_checked_at     timestamptz;
ALTER TABLE loadtest_domains ADD COLUMN IF NOT EXISTS last_error          text;

CREATE TABLE IF NOT EXISTS loadtest_usage (
    project_id  bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    month       date NOT NULL,                      -- first day of the month (UTC)
    vu_minutes  numeric NOT NULL DEFAULT 0,
    PRIMARY KEY (project_id, month)
);

-- One row per region runner of a run. The runner writes its own row; loadtest-ctl merges the rows into
-- loadtest_runs.live / summary (stats are mergeable histograms) and decides the final state.
CREATE TABLE IF NOT EXISTS loadtest_run_shards (
    run_id       bigint NOT NULL REFERENCES loadtest_runs(id) ON DELETE CASCADE,
    region       text NOT NULL,
    share        double precision NOT NULL DEFAULT 1,
    state        text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'running', 'done', 'aborted', 'error')),
    live         jsonb,
    stats        jsonb,                             -- cumulative engine.Stats
    summary      jsonb,                             -- final shard summary
    error        text,
    abort_reason text,
    started_at   timestamptz,
    finished_at  timestamptz,
    updated_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (run_id, region)
);
