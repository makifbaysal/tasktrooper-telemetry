-- Alert muting and maintenance.
ALTER TABLE monitors ADD COLUMN IF NOT EXISTS muted_until timestamptz;
CREATE TABLE IF NOT EXISTS maintenance_windows (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name        text NOT NULL,
    starts_at   timestamptz NOT NULL,
    ends_at     timestamptz NOT NULL,
    scope       jsonb NOT NULL DEFAULT '{}',              -- { services?: [], monitorIds?: [] }; empty = whole project
    created_by  bigint REFERENCES users(id),
    CHECK (ends_at > starts_at)
);

-- Incident 'pending': monitor condition met but forMin not elapsed yet; becomes 'firing' or is resolved quietly.
ALTER TABLE incidents DROP CONSTRAINT IF EXISTS incidents_state_check;
ALTER TABLE incidents ADD CONSTRAINT incidents_state_check CHECK (state IN ('pending', 'firing', 'acknowledged', 'resolved'));
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS quiet boolean NOT NULL DEFAULT false;  -- resolved from pending, never notified

