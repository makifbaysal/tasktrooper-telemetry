-- Cloud integrations (ADR-012), infra metadata, alert muting. Additive and idempotent.

-- Encrypted secrets entered in the UI (AES-256-GCM with TT_SECRETS_KEY). credentials_ref = 'secret:<id>'.
CREATE TABLE IF NOT EXISTS secrets (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name        text NOT NULL,
    nonce       bytea NOT NULL,
    ciphertext  bytea NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    rotated_at  timestamptz
);

CREATE TABLE IF NOT EXISTS integrations (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    provider        text NOT NULL CHECK (provider IN ('aws', 'gcp', 'vercel', 'neon')),
    name            text NOT NULL,
    -- aws:    { "roleArn": "...", "externalId": "...", "regions": ["eu-central-1"], "services": ["rds","elasticache","msk","sqs"] }
    -- gcp:    { "projectIds": ["shop-prod"], "services": ["cloudsql","memorystore","pubsub"] }
    -- vercel: { "teamId": "team_x", "projectMap": { "<vercel project>": "<service name>" }, "drainSecretRef": "secret:12" }
    -- neon:   { "orgId": "org-x", "projectIds": [] }  (empty = all)
    config          jsonb NOT NULL DEFAULT '{}',
    credentials_ref text,                                  -- secret:<id> | env:NAME | file:/path
    status          text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'ok', 'error', 'disabled')),
    error           text,
    last_sync_at    timestamptz,
    resources       integer NOT NULL DEFAULT 0,            -- discovered resource count
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, provider, name)
);

-- Deploy markers from outside the span pipeline (Vercel deployments, CI webhooks). api merges with telemetry.deploys.
CREATE TABLE IF NOT EXISTS deploy_markers (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id     bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    service        text NOT NULL,
    env            text NOT NULL DEFAULT 'production',
    version        text NOT NULL,                          -- git sha / deployment id
    source         text NOT NULL CHECK (source IN ('vercel', 'ci', 'manual', 'aws', 'gcp')),
    integration_id bigint REFERENCES integrations(id) ON DELETE SET NULL,
    url            text,
    commit_message text,
    author         text,
    state          text NOT NULL DEFAULT 'ready',           -- building | ready | error | canceled
    ts             timestamptz NOT NULL,
    external_id    text,
    UNIQUE (project_id, source, external_id)
);
CREATE INDEX IF NOT EXISTS deploy_markers_service ON deploy_markers (project_id, service, ts DESC);

