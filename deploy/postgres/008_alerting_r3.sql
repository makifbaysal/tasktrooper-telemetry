-- Alerting round 3 (from services/alerting). Additive, idempotent.

-- 1. KPI rule options (mirrors monitors.condition): { "renotifyMin": 30 } re-sends a still-firing,
--    unacknowledged KPI incident every renotifyMin minutes (reminder n is sent once per incident).
ALTER TABLE kpi_alert_rules ADD COLUMN IF NOT EXISTS condition jsonb NOT NULL DEFAULT '{}';

-- 2. Stream-rule hand-off between alert-engine shards (TT_ALERT_SHARDS > 1). The stream consumer (holder of
--    shard 0) evaluates every stream rule; a hit on a monitor owned by another shard is written here and announced
--    with NOTIFY tt_stream_hit (payload = monitor id). The owning replica LISTENs (and polls every second), deletes
--    the rows of its shards and applies them (escalate only). Rows are ephemeral: older than 5 minutes are dropped.
--    kind: 'breach' = in-memory window already over the threshold (value/detail); 'eval' = re-evaluate in ClickHouse.
CREATE UNLOGGED TABLE IF NOT EXISTS alert_stream_hits (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monitor_id  bigint NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
    kind        text NOT NULL CHECK (kind IN ('breach', 'eval')),
    value       double precision,
    detail      jsonb NOT NULL DEFAULT '{}',
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS alert_stream_hits_created ON alert_stream_hits (created_at);

-- 3. Slack App threads (contracts §17): an incident acknowledged in the dashboard / Slack is announced in the
--    firing message's thread. The alert-engine enqueues kind 'acknowledged' for slack:<channel id> targets.
ALTER TABLE notifications DROP CONSTRAINT IF EXISTS notifications_kind_check;
ALTER TABLE notifications ADD CONSTRAINT notifications_kind_check CHECK (kind IN ('firing', 'resolved', 'reminder', 'acknowledged'));
