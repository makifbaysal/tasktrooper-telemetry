-- AI usage quota (ADR-018, contracts §19). Owner: services/pkg/aiquota (codeintel writes usage, alert-engine sends
-- threshold notifications, api serves Settings → Usage). Additive and idempotent.

-- Limits: NULL = plan default (TT_AI_PLAN_CREDITS), -1 = unlimited. ai_notify uses the monitor channel format
-- (slack:<channel id>#name, slack:https://hooks.slack.com/…, email:<address>, channel names).
ALTER TABLE orgs         ADD COLUMN IF NOT EXISTS ai_monthly_credits integer;
ALTER TABLE orgs         ADD COLUMN IF NOT EXISTS ai_notify text[] NOT NULL DEFAULT '{}';
-- Member cap: NULL = none; applies only to work the member started.
ALTER TABLE memberships  ADD COLUMN IF NOT EXISTS ai_monthly_credits integer;
-- Who asked for the pending analysis (api: session user; NULL = api key, webhook or other automatic work).
ALTER TABLE repositories ADD COLUMN IF NOT EXISTS analyze_requested_by bigint REFERENCES users(id) ON DELETE SET NULL;
-- Summary of the last successful analysis written by codeintel:
--   { sha, items, llmItems, incremental, llm: { status: ok|disabled|quota_exceeded, reason?, credits, skipped? } }
ALTER TABLE repositories ADD COLUMN IF NOT EXISTS analysis jsonb;

-- Usage ledger: one row per LLM call. The monthly usage is SUM(credits) over the UTC calendar month (no counters).
-- 1 credit = 0.01 USD of model cost.
CREATE TABLE IF NOT EXISTS ai_usage (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id        bigint NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    project_id    bigint REFERENCES projects(id) ON DELETE SET NULL,
    user_id       bigint REFERENCES users(id) ON DELETE SET NULL,      -- NULL = automatic work
    feature       text NOT NULL,                                       -- codeintel.enrich | codeintel.suggest | rca | other
    model         text NOT NULL,
    input_tokens  integer NOT NULL,
    output_tokens integer NOT NULL,
    credits       numeric(12, 4) NOT NULL,
    ref           text NOT NULL DEFAULT '',                            -- e.g. 'repo:12'
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ai_usage_org_created ON ai_usage (org_id, created_at);
CREATE INDEX IF NOT EXISTS ai_usage_org_user_created ON ai_usage (org_id, user_id, created_at);

-- Threshold notifications sent (one per org + month + threshold).
CREATE TABLE IF NOT EXISTS ai_quota_alerts (
    org_id    bigint NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    period    date NOT NULL,                                           -- first day of the UTC month
    threshold smallint NOT NULL CHECK (threshold IN (80, 100)),
    sent_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (org_id, period, threshold)
);

-- Notification kind 'ai_quota' (no incident; payload { orgId, projectId, period, threshold, used, limit, resetsAt }).
ALTER TABLE notifications DROP CONSTRAINT IF EXISTS notifications_kind_check;
ALTER TABLE notifications ADD CONSTRAINT notifications_kind_check
    CHECK (kind IN ('firing', 'resolved', 'reminder', 'acknowledged', 'ai_quota'));
