-- TaskTrooper Telemetry · Postgres metadata schema. Owner: services/api. See .ai/data-model.md.
-- Ids are bigint identity; string slugs (database/cluster ids used in URLs and ClickHouse) are unique per project.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS orgs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    plan        text NOT NULL DEFAULT 'free',
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       text NOT NULL UNIQUE,
    name        text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS memberships (
    org_id   bigint NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    user_id  bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role     text NOT NULL CHECK (role IN ('owner', 'admin', 'member', 'viewer')),
    PRIMARY KEY (org_id, user_id)
);

CREATE TABLE IF NOT EXISTS projects (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      bigint NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    name        text NOT NULL,
    slug        text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (org_id, slug)
);

CREATE TABLE IF NOT EXISTS api_keys (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name            text NOT NULL,
    kind            text NOT NULL CHECK (kind IN ('ingest', 'api')),
    hash            bytea NOT NULL UNIQUE,                 -- sha256(key)
    prefix          text NOT NULL,                         -- first 8 chars, for display
    allowed_origins text[] NOT NULL DEFAULT '{}',          -- browser ingest keys; empty = any
    rate_limit_rps  integer,                               -- null = plan default
    revoked_at      timestamptz,
    last_used_at    timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS services (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name        text NOT NULL,
    type        text NOT NULL CHECK (type IN ('api', 'worker', 'web', 'mobile')),
    language    text,
    framework   text,
    owner       text,
    repo        text,
    first_seen  timestamptz NOT NULL DEFAULT now(),
    last_seen   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, name)
);

CREATE TABLE IF NOT EXISTS endpoints (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id  bigint NOT NULL REFERENCES services(id) ON DELETE CASCADE,
    method      text NOT NULL,                              -- GET/POST/...; 'CONSUME' for consumer processes, 'VIEW' for client screens
    route       text NOT NULL,
    source      text NOT NULL CHECK (source IN ('observed', 'code', 'both')),
    code_ref    jsonb,
    first_seen  timestamptz NOT NULL DEFAULT now(),
    last_seen   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (service_id, method, route)
);

CREATE TABLE IF NOT EXISTS notification_channels (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name        text NOT NULL,                              -- '#orders-oncall', 'pagerduty:payments'
    type        text NOT NULL CHECK (type IN ('slack', 'pagerduty', 'email', 'webhook', 'opsgenie')),
    config      jsonb NOT NULL DEFAULT '{}',                -- secrets by reference only
    UNIQUE (project_id, name)
);

CREATE TABLE IF NOT EXISTS kpis (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name        text NOT NULL,
    description text,
    owner       text,
    target      jsonb NOT NULL,                             -- { kind: endpoint|consumer|view, service, ref }
    sli         text NOT NULL CHECK (sli IN ('latency', 'availability', 'success_rate')),
    good_when   jsonb NOT NULL,                             -- { latencyMs?, statusBelow?, ... }
    objective   real NOT NULL CHECK (objective > 0 AND objective < 1),
    "window"    text NOT NULL CHECK ("window" IN ('7d', '28d')),
    source      text NOT NULL CHECK (source IN ('code', 'template', 'manual')),
    created_by  bigint REFERENCES users(id),
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS kpi_alert_rules (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kpi_id       bigint NOT NULL REFERENCES kpis(id) ON DELETE CASCADE,
    kind         text NOT NULL CHECK (kind IN ('burn_rate', 'below_target')),
    long_window  text,
    short_window text,
    threshold    real NOT NULL,
    severity     text NOT NULL CHECK (severity IN ('critical', 'warning', 'info')),
    channels     text[] NOT NULL DEFAULT '{}'
);

-- kind: latency | error_rate | throughput | apdex | log_pattern | log_count | anomaly | consumer_lag | dlq | rum_vital | crash_rate | custom
-- query: rule definition by kind. For consumer_lag:
--   { "clusterId": "kafka-main", "group": "order-events.fulfilment", "topic": "orders.created",
--     "metric": "lag|time_behind|partition_lag|growing|not_drained|rebalances", "threshold": 10000, "forMin": 5 }
CREATE TABLE IF NOT EXISTS monitors (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name          text NOT NULL,
    kind          text NOT NULL,
    target        jsonb NOT NULL DEFAULT '{}',              -- { service, endpoint?, process?, view? }
    query         jsonb NOT NULL,
    condition     jsonb NOT NULL,                           -- { op: '>', threshold, forMin, window }
    severity      text NOT NULL CHECK (severity IN ('critical', 'warning', 'info')),
    channels      text[] NOT NULL DEFAULT '{}',
    source        text NOT NULL CHECK (source IN ('manual', 'suggested', 'template')),
    status        text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'muted', 'draft')),
    state         text NOT NULL DEFAULT 'ok' CHECK (state IN ('ok', 'pending', 'firing', 'no_data')),
    state_since   timestamptz NOT NULL DEFAULT now(),
    last_value    double precision,
    last_eval_at  timestamptz,
    suggestion_id bigint,
    created_by    bigint REFERENCES users(id),
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS monitors_project ON monitors (project_id) WHERE status = 'active';

CREATE TABLE IF NOT EXISTS incidents (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    monitor_id   bigint REFERENCES monitors(id) ON DELETE SET NULL,
    kpi_id       bigint REFERENCES kpis(id) ON DELETE SET NULL,
    title        text NOT NULL,
    severity     text NOT NULL,
    service      text,
    endpoint     text,
    state        text NOT NULL CHECK (state IN ('firing', 'acknowledged', 'resolved')),
    started_at   timestamptz NOT NULL DEFAULT now(),
    acked_at     timestamptz,
    acked_by     bigint REFERENCES users(id),
    resolved_at  timestamptz,
    peak_value   double precision,
    root_cause   jsonb                                     -- RcaResult snapshot
);
CREATE INDEX IF NOT EXISTS incidents_open ON incidents (project_id, service) WHERE state <> 'resolved';
-- One open incident per monitor.
CREATE UNIQUE INDEX IF NOT EXISTS incidents_one_open ON incidents (monitor_id) WHERE state <> 'resolved' AND monitor_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS incident_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id bigint NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    ts          timestamptz NOT NULL DEFAULT now(),
    kind        text NOT NULL,                              -- fired | acked | resolved | notified | comment | value
    data        jsonb NOT NULL DEFAULT '{}'
);

-- Outbox: alert-engine inserts, notifier delivers (FOR UPDATE SKIP LOCKED).
CREATE TABLE IF NOT EXISTS notifications (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id  bigint REFERENCES incidents(id) ON DELETE CASCADE,
    channel      text NOT NULL,
    kind         text NOT NULL CHECK (kind IN ('firing', 'resolved', 'reminder')),
    payload      jsonb NOT NULL,
    dedupe_key   text NOT NULL UNIQUE,
    attempts     integer NOT NULL DEFAULT 0,
    next_at      timestamptz NOT NULL DEFAULT now(),
    sent_at      timestamptz,
    error        text
);
CREATE INDEX IF NOT EXISTS notifications_due ON notifications (next_at) WHERE sent_at IS NULL;

CREATE TABLE IF NOT EXISTS error_issues (
    project_id  bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    fingerprint numeric(20, 0) NOT NULL,                    -- UInt64 from ClickHouse
    status      text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved', 'ignored')),
    assignee    bigint REFERENCES users(id),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (project_id, fingerprint)
);

CREATE TABLE IF NOT EXISTS repositories (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id        bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    provider          text NOT NULL CHECK (provider IN ('github', 'gitlab', 'bitbucket')),
    full_name         text NOT NULL,
    default_branch    text NOT NULL DEFAULT 'main',
    last_analyzed_sha text,
    status            text NOT NULL DEFAULT 'pending',
    UNIQUE (project_id, provider, full_name)
);

CREATE TABLE IF NOT EXISTS inventory_items (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id bigint NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    kind          text NOT NULL CHECK (kind IN ('endpoint', 'consumer', 'cron', 'view', 'dependency')),
    key           text NOT NULL,
    source        text,
    file          text,
    line          integer,
    meta          jsonb NOT NULL DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS alert_suggestions (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id        bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    inventory_item_id bigint REFERENCES inventory_items(id) ON DELETE SET NULL,
    monitor_draft     jsonb NOT NULL,
    rationale         text NOT NULL,
    confidence        real NOT NULL,
    state             text NOT NULL DEFAULT 'proposed' CHECK (state IN ('proposed', 'accepted', 'rejected'))
);

-- Infrastructure. slug = id used by UI routes and ClickHouse (database_id / cluster_id).
CREATE TABLE IF NOT EXISTS databases (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id        bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    slug              text NOT NULL,
    name              text NOT NULL,                       -- matches dependency name "<engine> · <name>"
    engine            text NOT NULL CHECK (engine IN ('postgres', 'mysql', 'redis', 'mongodb')),
    host              text NOT NULL,
    port              integer NOT NULL,
    collector         text NOT NULL CHECK (collector IN ('agent', 'cloud', 'direct')),
    username          text,                                -- monitoring user (default trooper_monitor)
    credentials_ref   text,                                -- secret store reference, never the secret
    cloud_resource_id text,
    env               text NOT NULL DEFAULT 'production',
    created_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, slug)
);

CREATE TABLE IF NOT EXISTS broker_clusters (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    slug            text NOT NULL,
    name            text NOT NULL,
    kind            text NOT NULL CHECK (kind IN ('kafka', 'rabbitmq')),
    endpoint        text NOT NULL,                         -- kafka: bootstrap servers; rabbitmq: management API URL
    vhost           text,
    auth            jsonb NOT NULL DEFAULT '{}',           -- { mechanism: none|plain|scram-sha-512|iam, tls: bool }
    credentials_ref text,
    collector       text NOT NULL DEFAULT 'agent' CHECK (collector IN ('agent', 'cloud', 'direct')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, slug)
);

-- Consumer group ↔ service mapping learned from SDK spans (messaging.consumer.group.name) or set manually.
CREATE TABLE IF NOT EXISTS consumer_group_owners (
    cluster_id      bigint NOT NULL REFERENCES broker_clusters(id) ON DELETE CASCADE,
    consumer_group  text NOT NULL,
    service_id      bigint REFERENCES services(id) ON DELETE SET NULL,
    process         text,
    source          text NOT NULL CHECK (source IN ('observed', 'manual')),
    PRIMARY KEY (cluster_id, consumer_group)
);

CREATE TABLE IF NOT EXISTS loadtest_scenarios (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name        text NOT NULL,
    spec        jsonb NOT NULL,
    source      text NOT NULL CHECK (source IN ('manual', 'generated')),
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS loadtest_runs (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id       bigint NOT NULL REFERENCES loadtest_scenarios(id) ON DELETE CASCADE,
    state             text NOT NULL,
    started_at        timestamptz,
    finished_at       timestamptz,
    summary           jsonb,
    thresholds_passed boolean
);

CREATE TABLE IF NOT EXISTS schema_migrations (
    version    text PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
);
