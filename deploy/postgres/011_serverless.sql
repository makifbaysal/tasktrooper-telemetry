-- Serverless functions: AWS Lambda + Azure Functions (ADR-020, contracts §21). Owner: services/integrations.
-- Additive and idempotent.

-- Azure integrations (provider='azure'): config = { "tenantId", "clientId", "subscriptionIds": [], "resourceGroups"?: [], "env"? },
-- credentials_ref → client secret. Recreates the 009 constraint with every existing value + 'azure'.
ALTER TABLE integrations DROP CONSTRAINT IF EXISTS integrations_provider_check;
ALTER TABLE integrations ADD CONSTRAINT integrations_provider_check
    CHECK (provider IN ('aws', 'gcp', 'vercel', 'neon', 'slack', 'github', 'azure'));

-- One row per Lambda function (aws-<region>-<name>) or Azure Function App (azure-<app>; functions in meta.functions).
-- Discovery upserts (integration_id set); functions not found any more get missing = true (rows are never deleted).
CREATE TABLE IF NOT EXISTS serverless_functions (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id     bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    integration_id bigint REFERENCES integrations(id) ON DELETE SET NULL,
    provider       text NOT NULL CHECK (provider IN ('aws', 'azure')),
    slug           text NOT NULL,                          -- aws-<region>-<name> | azure-<app>
    name           text NOT NULL,
    app            text,                                   -- Azure: function app name (name = app)
    region         text NOT NULL DEFAULT '',
    runtime        text NOT NULL DEFAULT '',
    memory_mb      integer,
    timeout_s      integer,
    arch           text NOT NULL DEFAULT '',
    triggers       text[] NOT NULL DEFAULT '{}',           -- 'api', 'http', 'schedule', 'sqs:orders', 'kinesis:..', 'dynamodb:..'
    service        text NOT NULL,                          -- span service.name (default name; tag/app setting 'tasktrooper.service')
    url            text,
    meta           jsonb NOT NULL DEFAULT '{}',            -- arn, plan (Consumption|Flex|Premium), functions[] (Azure), tags
    last_seen_at   timestamptz NOT NULL DEFAULT now(),
    missing        boolean NOT NULL DEFAULT false,
    created_at     timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, slug)
);
CREATE INDEX IF NOT EXISTS serverless_functions_integration ON serverless_functions (integration_id);
CREATE INDEX IF NOT EXISTS serverless_functions_service ON serverless_functions (project_id, service);
