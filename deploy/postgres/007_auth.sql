-- User identity: OIDC + sessions, roles, audit log (ADR-016, contracts §15). Owner: services/api. Additive and idempotent.
-- Org roles live in memberships.role (owner | admin | member | viewer, 001_init.sql).

ALTER TABLE users ADD COLUMN IF NOT EXISTS oidc_subject  text;         -- OIDC `sub` of TT_OIDC_ISSUER
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_login_at timestamptz;
CREATE UNIQUE INDEX IF NOT EXISTS users_oidc_subject ON users (oidc_subject) WHERE oidc_subject IS NOT NULL;

ALTER TABLE api_keys ADD COLUMN IF NOT EXISTS created_by   bigint REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE api_keys ADD COLUMN IF NOT EXISTS last_used_at timestamptz;

-- Browser sessions (cookie tt_session). id = hex(sha256(cookie value)): a database read never yields a usable cookie.
-- Sliding expiry: every request seen after a minute pushes expires_at to now() + 7 days.
CREATE TABLE IF NOT EXISTS sessions (
    id            text PRIMARY KEY,
    user_id       bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at    timestamptz NOT NULL DEFAULT now(),
    expires_at    timestamptz NOT NULL,
    last_seen_at  timestamptz NOT NULL DEFAULT now(),
    user_agent    text
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions (user_id);
CREATE INDEX IF NOT EXISTS sessions_expires ON sessions (expires_at);

-- Pending OIDC logins (Authorization Code + PKCE): state → verifier/nonce/redirect, 10 minutes, deleted on callback.
CREATE TABLE IF NOT EXISTS oidc_login_states (
    state       text PRIMARY KEY,
    verifier    text NOT NULL,
    nonce       text NOT NULL,
    redirect    text NOT NULL DEFAULT '',
    expires_at  timestamptz NOT NULL
);

-- Who changed what. action = "METHOD /route/pattern" (or login/logout), target = the entity id.
CREATE TABLE IF NOT EXISTS audit_log (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      bigint NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    project_id  bigint REFERENCES projects(id) ON DELETE SET NULL,
    user_id     bigint REFERENCES users(id) ON DELETE SET NULL,
    api_key_id  bigint REFERENCES api_keys(id) ON DELETE SET NULL,
    action      text NOT NULL,
    target      text NOT NULL DEFAULT '',
    meta        jsonb NOT NULL DEFAULT '{}',
    at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS audit_log_org_at ON audit_log (org_id, at DESC);

-- Load test domain verification request (POST /loadtests/domains/{id}/verify); loadtest-ctl re-checks the domain.
ALTER TABLE IF EXISTS loadtest_domains ADD COLUMN IF NOT EXISTS verify_requested_at timestamptz;

