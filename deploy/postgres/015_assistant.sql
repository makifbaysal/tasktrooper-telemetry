-- Dashboard assistant (AI chat, ADR-033, .ai/assistant.md). Threads are private to a user inside a project.
-- Additive and idempotent.
CREATE TABLE IF NOT EXISTS assistant_threads (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      bigint NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    project_id  bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    user_id     bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title       text NOT NULL DEFAULT '',
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS assistant_threads_user ON assistant_threads (project_id, user_id, updated_at DESC);

-- content: the UI shape (user: text/refs/attachments, assistant: blocks/usage).
-- transcript: { messages: [...], pending: [...] } model-format messages of an assistant turn (tool calls + results).
CREATE TABLE IF NOT EXISTS assistant_messages (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id   bigint NOT NULL REFERENCES assistant_threads(id) ON DELETE CASCADE,
    org_id      bigint NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    project_id  bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    role        text NOT NULL CHECK (role IN ('user', 'assistant')),
    content     jsonb NOT NULL,
    transcript  jsonb,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS assistant_messages_thread ON assistant_messages (thread_id, id);

-- Uploaded images (PNG, JPEG, GIF, WebP; at most 5 MB each).
CREATE TABLE IF NOT EXISTS assistant_attachments (
    id          uuid PRIMARY KEY,
    org_id      bigint NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    project_id  bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    user_id     bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    media_type  text NOT NULL CHECK (media_type IN ('image/png', 'image/jpeg', 'image/gif', 'image/webp')),
    size        integer NOT NULL,
    data        bytea NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS assistant_attachments_user ON assistant_attachments (project_id, user_id, created_at);
